def color_name(hex_code: str | None) -> str:
    """Bambu's name for a colour, or the placeholder when it is not one of theirs."""
    if not hex_code:
        return UNKNOWN_COLOR
    return COLOR_NAMES.get(str(hex_code).strip().upper(), UNKNOWN_COLOR)
